def exclude_block(exclude_list, limit, mode=MODE_SOURCE) -> str:
    """สร้างบล็อกรายการข้อที่มีอยู่แล้ว

    exclude_list รับได้ 2 แบบ
      - str            : คำถามอย่างเดียว (แบบเดิม)
      - {"question", "answer"} : คำถามพร้อมเฉลย (แบบใหม่)
    """
    items = list(exclude_list or [])[:limit]
    if not items:
        return ""

    has_answer = any(isinstance(x, dict) and x.get("answer") for x in items)

    # ไม่มีเฉลยส่งมา -> ใช้ข้อความเดิมทุกตัวอักษร
    if not has_answer:
        lines = [str(x.get("question") if isinstance(x, dict) else x) for x in items]
        return "หลีกเลี่ยงการตั้งคำถามคล้ายกับ:\n" + "\n".join(f"- {q}" for q in lines) + "\n"

    lines = []
    for x in items:
        if isinstance(x, dict):
            q = str(x.get("question") or "").strip()
            a = str(x.get("answer") or "").strip()
        else:
            q, a = str(x).strip(), ""
        if not q:
            continue
        lines.append(f"- ถาม: {q}" + (f"\n  ตอบ: {a}" if a else ""))

    if not lines:
        return ""

    tail = (
        "ถือว่าซ้ำเมื่อวัดกฎเดียวกันและใช้ข้อมูลชุดเดียวกัน\n"
        "ถ้าใช้กฎเดียวกันแต่เปลี่ยนข้อมูลในโจทย์เป็นชุดใหม่ ไม่ถือว่าซ้ำ\n"
        if normalize_mode(mode) == MODE_APPLIED else ""
    )
    return "ข้อสอบที่มีอยู่แล้ว ห้ามออกข้อที่ซ้ำกับรายการนี้:\n" + "\n".join(lines) + "\n" + tail


