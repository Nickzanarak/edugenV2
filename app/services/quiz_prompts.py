def normalize_mode(mode) -> str:
    """กันค่าแปลกปลอม ถ้าไม่รู้จักให้ถอยกลับไปโหมดเดิมเสมอ"""
    key = (mode or MODE_SOURCE).strip().lower()
    return key if key in VALID_MODES else MODE_SOURCE


