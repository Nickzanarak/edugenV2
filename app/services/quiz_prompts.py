def topic_block(topic_hints, n, mode=MODE_SOURCE) -> str:
    """สร้างบล็อกหัวข้อ

    โหมดเดิม: ส่งรายการหัวข้อไปเหมือนเดิม เพื่อให้ข้อสอบครอบคลุมทั้งเอกสาร

    โหมดประยุกต์: ไม่ส่งรายการ เพราะการบังคับ "หัวข้อละ 1 ข้อ" จะลากไปหา
    หัวข้อที่ประยุกต์ไม่ได้ (นิยาม เกร็ดความรู้) เมื่อขอข้อสอบจำนวนมาก
    ปล่อยให้ AI เลือกเองจากส่วนที่มีกฎหรือสูตร ตามที่กติกาในโหมดนี้กำหนดไว้
    """
    if normalize_mode(mode) == MODE_APPLIED:
        return ""
    if not topic_hints:
        return ""
    return (
        "ให้สร้าง 'หัวข้อละ 1 ข้อ' จากหัวข้อต่อไปนี้:\n"
        + "\n".join(f"- {t}" for t in topic_hints[:n])
        + "\n"
    )


