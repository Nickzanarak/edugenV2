def angle_cap(count: int, tries: int = 0) -> int:
    """มุมเดียวใช้ได้กี่ข้อ ~1 ใน 3 ของชุด (อย่างน้อย 2) ผ่อนเพิ่มเมื่อหาไม่ครบ"""
    n = max(1, int(count or 1))
    base = max(2, -(-n // 3))          # ปัดขึ้น
    return base + max(0, tries) // 2


