def _walk_stride(total: int, count: int) -> int:
    """ระยะก้าวสำหรับเดินเลือกกฎ

    ต้องหารร่วมมากกับ total ได้ 1 เท่านั้น เพราะคุณสมบัตินี้การันตีว่า
    เดินไปเรื่อย ๆ จะแตะครบทุกกฎก่อนวนกลับมาซ้ำ (ไม่มีกฎไหนถูกข้ามถาวร)
    เลือกค่าที่ใกล้ total/count ที่สุด เพื่อให้กฎในรอบเดียวกันกระจายทั่วเอกสาร
    """
    if total <= 1:
        return 1
    target = max(1, round(total / max(1, count)))
    for delta in range(total):
        for s in (target + delta, target - delta):
            if 1 <= s < total and math.gcd(s, total) == 1:
                return s
    return 1


