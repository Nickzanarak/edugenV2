def mcq_json(choices_example: str, answer_options: str) -> str:
    """รูปแบบ JSON ของข้อสอบปรนัย โหมดเดิม"""
    tail = (
        f'"question":"...","choices":[{choices_example}],'
        f'"answer":"{answer_options}","explain":"...","topic":"..."'
    )
    return '{"questions":[{"type":"mcq",' + tail + "}]}"


# ---------------------------------------------------------------------------
# รายการหัวข้อ
# ---------------------------------------------------------------------------

def topic_block(topic_hints, n) -> str:
    """สร้างบล็อกหัวข้อ ให้ข้อสอบครอบคลุมทั้งเอกสาร (หัวข้อละ 1 ข้อ)"""
    if not topic_hints:
        return ""
    return (
        "ให้สร้าง 'หัวข้อละ 1 ข้อ' จากหัวข้อต่อไปนี้:\n"
        + "\n".join(f"- {t}" for t in topic_hints[:n])
        + "\n"
    )


# ---------------------------------------------------------------------------
# รายการห้ามซ้ำ
# ---------------------------------------------------------------------------

def exclude_block(exclude_list, limit, tail: str = "") -> str:
    """สร้างบล็อกรายการข้อที่มีอยู่แล้ว

    exclude_list รับได้ 2 แบบ
      - str            : คำถามอย่างเดียว (แบบเดิม)
      - {"question", "answer"} : คำถามพร้อมเฉลย (แบบใหม่)

    tail = ข้อความต่อท้ายที่โหมดอื่นส่งมาเพิ่ม โหมดเดิมไม่ส่ง (ค่าว่าง)
    """
    items = list(exclude_list or [])[:limit]
    if not items:
        return ""

    has_answer = any(isinstance(x, dict) and x.get("answer") for x in items)

    # ไม่มีเฉลยส่งมา -> ใช้ข้อความเดิมทุกตัวอักษร
    if not has_answer:
        lines = [str(x.get("question") if isinstance(x, dict) else x) for x in items]
        return "หลีกเลี่ยงการตั้งคำถามคล้ายกับ:\n" + "\n".join(f"- {q}" for q in lines) + "\n"

    lines = []
    for x in items:
        if isinstance(x, dict):
            q = str(x.get("question") or "").strip()
            a = str(x.get("answer") or "").strip()
        else:
            q, a = str(x).strip(), ""
        if not q:
            continue
        lines.append(f"- ถาม: {q}" + (f"\n  ตอบ: {a}" if a else ""))

    if not lines:
        return ""

    return "ข้อสอบที่มีอยู่แล้ว ห้ามออกข้อที่ซ้ำกับรายการนี้:\n" + "\n".join(lines) + "\n" + tail


