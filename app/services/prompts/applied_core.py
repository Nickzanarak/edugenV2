def _walk_stride(total: int, count: int) -> int:
    """ระยะก้าวสำหรับเดินเลือกกฎ

    ต้องหารร่วมมากกับ total ได้ 1 เท่านั้น เพราะคุณสมบัตินี้การันตีว่า
    เดินไปเรื่อย ๆ จะแตะครบทุกกฎก่อนวนกลับมาซ้ำ (ไม่มีกฎไหนถูกข้ามถาวร)
    เลือกค่าที่ใกล้ total/count ที่สุด เพื่อให้กฎในรอบเดียวกันกระจายทั่วเอกสาร
    """
    if total <= 1:
        return 1
    target = max(1, round(total / max(1, count)))
    for delta in range(total):
        for s in (target + delta, target - delta):
            if 1 <= s < total and math.gcd(s, total) == 1:
                return s
    return 1


def plan_rule_quota(rules, count: int, offset: int = 0):
    """แบ่งโควตาข้อให้แต่ละกฎ คืน [(ชื่อกฎ, จำนวนข้อ), ...]

    ถ้ากฎเยอะกว่าจำนวนข้อที่ขอ ให้เลือกกฎแบบกระจายทั่วเอกสาร
    ไม่ใช่หยิบแต่กฎแรก ๆ (ซึ่งมักเป็นกฎง่าย ๆ ที่อยู่ต้นบท)

    offset = จำนวนข้อสอบที่มีอยู่แล้ว ใช้หมุนจุดเริ่มของการเลือก
    เพราะถ้าไม่หมุน การเจนทีละชุด (ง่าย/กลาง/ยาก) จะเลือกกฎชุดเดิมทุกครั้ง
    วัดจากของจริง: เอกสารมี 6 กฎ เจนทีละ 5 ข้อ 3 รอบ ได้กฎชุดเดิม 0,1,2,4,5
    ทุกรอบ กฎที่ 3 จึงไม่เคยถูกออกข้อสอบเลย
    """
    items = [str(r).strip() for r in (rules or []) if str(r).strip()]
    n = max(1, int(count or 1))
    if not items:
        return []

    if n < len(items):
        # เดินเลือกกฎเป็น "รอยเดิน" ต่อเนื่อง ไม่ใช่หมุนรายการแล้วเลือกใหม่
        # ก้าวละ stride ที่หารร่วมกับจำนวนกฎได้ 1 จึงเดินครบทุกกฎก่อนวนซ้ำ
        # และรอบถัดไปเดินต่อจากตำแหน่งเดิม (offset) ไม่ย้อนไปทับของเก่า
        total = len(items)
        stride = _walk_stride(total, n)
        start = max(0, int(offset))
        idxs = []
        for i in range(total):               # กันกรณีชนกันเอง เดินต่อจนได้ครบ n
            if len(idxs) >= n:
                break
            j = ((start + i) * stride) % total
            if j not in idxs:
                idxs.append(j)
        return [(items[j], 1) for j in idxs]

    base, remainder = divmod(n, len(items))
    # กฎน้อยกว่าจำนวนข้อ -> ได้ทุกกฎอยู่แล้ว หมุนเฉพาะว่ากฎไหนได้ข้อเพิ่ม
    k = (int(offset) % len(items)) if offset else 0
    rotated = items[k:] + items[:k]
    return [(r, base + (1 if i < remainder else 0)) for i, r in enumerate(rotated)]


