def tf_review_prompt(items, context: str = "") -> str:
    """สร้างคำสั่งตรวจทานข้อสอบถูก/ผิดทั้งชุดในครั้งเดียว

    จงใจไม่ส่งเฉลยเดิมไปให้เห็น เพราะพบว่าการเห็นเฉลยเดิมทำให้ AI
    มีแนวโน้มเห็นด้วยตามแทนที่จะตัดสินใหม่อย่างอิสระ

    ถ้าส่ง context มาด้วย จะตรวจ "ขอบเขต" เพิ่มอีกชั้น คือดูว่าข้อนั้น
    ใช้กฎที่เนื้อหาสอนไว้จริงหรือเปล่า (กันกรณีเนื้อหาสอนแค่บวกลบ แต่ AI ออกโจทย์คูณ)
    ตั้งใจให้เอนไปทาง "อยู่ในขอบเขต" เมื่อไม่แน่ใจ เพราะการตีตกผิดทำให้ทิ้งข้อที่ดีไปเปล่า ๆ
    """
    body = "\n".join(f"[{i}] {q.get('question', '')}" for i, q in enumerate(items))

    if not (context or "").strip():
        scope_rule = ""
        scope_field = ""
        scope_desc = ""
        scope_ref = ""
    else:
        scope_rule = (
            "- ตรวจขอบเขตด้วย: ข้อนั้นต้องตัดสินได้ด้วยกฎ สูตร หรือความรู้"
            " ที่ปรากฏใน 'เนื้อหาอ้างอิง' ท้ายคำสั่งนี้เท่านั้น\n"
            "  ถ้าต้องใช้วิธีหรือแนวคิดที่เนื้อหาไม่ได้สอน ให้ตอบ scope เป็น out\n"
            "  ถ้าไม่แน่ใจ ให้ตอบ in เสมอ ตีตกเฉพาะข้อที่หลุดขอบเขตอย่างชัดเจน\n"
        )
        scope_field = '"scope":"in|out",'
        scope_desc = "- scope คือผลตรวจขอบเขต in = ใช้กฎในเนื้อหา | out = ใช้วิธีนอกเนื้อหา\n"
        scope_ref = f"\nเนื้อหาอ้างอิง (ขอบเขตที่อนุญาต):\n{context}\n"

    return f"""ตัดสินว่าข้อความต่อไปนี้แต่ละข้อ ถูกต้องตามหลักวิชาหรือไม่

วิธีทำ
- ถ้าข้อความมีการคำนวณ ให้คำนวณใหม่ด้วยตัวเอง แล้วเทียบกับค่าที่ข้อความระบุ
  ค่าตรงกัน = true | ค่าไม่ตรงกัน = false
- ถ้าเป็นเนื้อหาภาษาหรือข้อเท็จจริง ให้ตัดสินตามหลักวิชา
{scope_rule}- ตัดสินแต่ละข้อแยกกันอย่างอิสระ ห้ามคำนึงถึงสัดส่วน true หรือ false ของทั้งชุด
- ต้องตอบให้ครบทุกข้อ ห้ามข้ามข้อใด

ตอบ JSON: {{"results":[{{"index":0,"explain":"...",{scope_field}"answer":"true|false"}}]}}
- index คือหมายเลขในวงเล็บเหลี่ยม
- explain คือวิธีคิดจนได้ผลนั้น เขียนให้กระชับและไม่แสดงความลังเล
{scope_desc}- answer คือผลการตัดสินของคุณ กรอกหลังเขียน explain เสร็จแล้ว

ข้อความที่ต้องตัดสิน:
{body}
{scope_ref}"""


