import pytest

from app.utils.nlp import same_question

T = 0.78      # เกณฑ์เดียวกับที่คลังใช้ (settings.NEAR_DUP_THRESHOLD)


# ----- โครงเดียวกัน เลขต่างกัน = คนละข้อ ต้องให้เข้าคลังได้ -----

@pytest.mark.parametrize("a,b", [
    # เคสจริง: ถามพจน์ที่ 7 กับพจน์ที่ 9 คำตอบ 30 กับ 38
    ("ลำดับเลขคณิตลำดับหนึ่งมีพจน์แรกเป็น 6 และผลต่างร่วมเป็น 4 พจน์ที่เจ็ดมีค่าเท่าใด",
     "ลำดับเลขคณิตลำดับหนึ่งมีพจน์แรกเป็น 6 และผลต่างร่วมเป็น 4 พจน์ที่อยู่ลำดับที่ 9 มีค่าเท่าใด"),
    # เคสจริง: คนละเลขหมด คนละแนวถาม
    ("ลำดับเรขาคณิตลำดับหนึ่งมีพจน์แรกเป็น 3 และอัตราส่วนร่วมเป็น 2 พจน์ที่หกมีค่าเท่าใด",
     "ลำดับเรขาคณิตลำดับหนึ่งมีพจน์แรกเป็น 5 และอัตราส่วนร่วมเป็น 3 พจน์ใดมีค่า 405"),
    ("ลำดับเลขคณิตลำดับหนึ่งมีพจน์แรกเป็น 6 และผลต่างร่วมเป็น 4 พจน์ที่เจ็ดมีค่าเท่าใด",
     "ลำดับเลขคณิตลำดับหนึ่งมีพจน์แรกเป็น 11 และผลต่างร่วมเป็น 3 พจน์ใดมีค่า 29"),
    # โหมดเดิมได้ประโยชน์ด้วย: ครั้งที่ 1 กับ 2 คนละสงคราม
    ("สงครามโลกครั้งที่ 2 เริ่มต้นในปี ค.ศ. ใด",
     "สงครามโลกครั้งที่ 1 เริ่มต้นในปี ค.ศ. ใด"),
    ("สงครามโลกครั้งที่สองเริ่มต้นในปี ค.ศ. ใด",
     "สงครามโลกครั้งที่หนึ่งเริ่มต้นในปี ค.ศ. ใด"),
])
def test_same_structure_different_numbers_is_not_duplicate(a, b):
    assert same_question(a, b, T) is False


# ----- ซ้ำจริง ต้องยังจับได้ -----

@pytest.mark.parametrize("a,b", [
    # เลขเดียวกันหมด ต่างแค่เขียน "หก" เป็นตัวหนังสือ กับ "6" เป็นตัวเลข
    ("ลำดับเรขาคณิตลำดับหนึ่งมีพจน์แรกเป็น 3 และอัตราส่วนร่วมเป็น 2 พจน์ที่หกมีค่าเท่าใด",
     "ลำดับเรขาคณิตลำดับหนึ่งมีพจน์แรกเป็น 3 และอัตราส่วนร่วมเป็น 2 พจน์ที่อยู่ลำดับที่ 6 มีค่าเท่าใด"),
    # ข้อความเหมือนกันเป๊ะ
    ("ลำดับเลขคณิตลำดับหนึ่งมีพจน์แรกเป็น 6 และผลต่างร่วมเป็น 4 พจน์ที่อยู่ลำดับที่ 9 มีค่าเท่าใด",
     "ลำดับเลขคณิตลำดับหนึ่งมีพจน์แรกเป็น 6 และผลต่างร่วมเป็น 4 พจน์ที่อยู่ลำดับที่ 9 มีค่าเท่าใด"),
    # โหมดเดิม: เรียบเรียงใหม่ เลขเดิม
    ("ในปี 2006 ระบบสุริยะมีดาวเคราะห์ 8 ดวง โลกอยู่ลำดับที่เท่าไหร่",
     "ปี 2006 ระบบสุริยะเหลือดาวเคราะห์ 8 ดวง โลกอยู่ลำดับที่เท่าใด"),
    # โหมดเดิม: ไม่มีเลขเลย ต้องถอยไปใช้ตัวหนังสืออย่างเดียวเหมือนเดิม
    ("ดาวเคราะห์ดวงใดใหญ่ที่สุดในระบบสุริยะ",
     "ดาวเคราะห์ดวงใดมีขนาดใหญ่ที่สุดในระบบสุริยะ"),
])
def test_real_duplicate_is_still_caught(a, b):
    assert same_question(a, b, T) is True


def test_one_side_without_numbers_falls_back_to_text():
    """ฝั่งเดียวมีเลข อีกฝั่งไม่มี เทียบเลขไม่ได้ ให้ใช้ผลจากตัวหนังสือ"""
    a = "ดาวเคราะห์ดวงใดใหญ่ที่สุดในระบบสุริยะ"
    b = "ดาวเคราะห์ดวงใดใหญ่ที่สุดในระบบสุริยะทั้ง 8 ดวง"
    assert same_question(a, b, T) is True


def test_below_text_threshold_is_never_duplicate():
    """ตัวหนังสือไม่คล้ายกันตั้งแต่แรก เลขเหมือนกันก็ไม่ถือว่าซ้ำ (ขั้นที่ 1 ตัดก่อน)"""
    a = "ลำดับเลขคณิต พจน์แรก 5 ผลต่างร่วม 3 พจน์ที่ 4 มีค่าเท่าใด"
    b = "รถคันหนึ่งวิ่ง 5 กิโลเมตรใน 3 นาที ใน 4 นาทีวิ่งได้กี่กิโลเมตร"
    assert same_question(a, b, T) is False
